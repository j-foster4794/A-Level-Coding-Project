using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class TutorialImage : MonoBehaviour // Autogenerated class declaration inherited from "MonoBehaviour" meaning the script can be attached to game objects
{
   [SerializeField] GameObject tutorialImage; // declaration of a gameobject meaning it can be viewed and have game objects attached to it using the visual editor 
   void Update() // the key Unity method "Update" is called every frame to constantly check and the void key word indicates no return value 
   {
        if (tutorialImage.activeSelf) // The tutorial menu only needs to be deactivated if it is not already deactivated
            {
                if (Input.GetKeyDown("escape")) // if the escape key is pressed down then it goes to set it as inactive
                {
                    tutorialImage.SetActive(false); // set the game object of the tutorial image menu to be deactivated.
                }
            }
   }
}